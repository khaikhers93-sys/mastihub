@app.route("/admin")
def admin():

    if not session.get("admin"):
        return redirect(url_for("login"))

    conn = get_db()

    store_orders = conn.execute("""
        SELECT o.id, o.amount, o.status, o.utr, o.created_at,
               u.username, p.name AS product_name
        FROM store_orders o
        JOIN users u ON u.id = o.user_id
        JOIN store_products p ON p.id = o.product_id
        ORDER BY o.id DESC
    """).fetchall()

    withdrawals = conn.execute("""
        SELECT withdrawals.*, users.username
        FROM withdrawals
        JOIN users ON users.id = withdrawals.user_id
        ORDER BY withdrawals.id DESC
    """).fetchall()

    users = conn.execute("""
        SELECT id, username, points
        FROM users
        ORDER BY id DESC
    """).fetchall()

    total_users = conn.execute(
        "SELECT COUNT(*) AS c FROM users"
    ).fetchone()["c"]

    total_points = conn.execute(
        "SELECT COALESCE(SUM(points), 0) AS s FROM users"
    ).fetchone()["s"]

    total_withdrawals = conn.execute(
        "SELECT COUNT(*) AS c FROM withdrawals"
    ).fetchone()["c"]

    approved_withdrawals = conn.execute("""
        SELECT COALESCE(SUM(amount), 0) AS s
        FROM withdrawals
        WHERE status = 'Paid'
    """).fetchone()["s"]

    pending_withdrawals = conn.execute("""
        SELECT COALESCE(SUM(amount), 0) AS s
        FROM withdrawals
        WHERE status = 'Pending'
    """).fetchone()["s"]

    # 1000 points = ₹100
    reward_value = total_points / 10

    total_revenue = conn.execute(
        "SELECT COALESCE(SUM(amount), 0) AS s FROM platform_revenue"
    ).fetchone()["s"]

    revenue_history = conn.execute("""
        SELECT id, amount, source, created_at
        FROM platform_revenue
        ORDER BY id DESC
    """).fetchall()

    admin_net = total_revenue - approved_withdrawals
    available_payout = max(0, admin_net)

    conn.close()

    return render_template(
        "admin.html",
        store_orders=store_orders,
        withdrawals=withdrawals,
        users=users,
        total_users=total_users,
        total_points=total_points,
        reward_value=reward_value,
        total_withdrawals=total_withdrawals,
        approved_withdrawals=approved_withdrawals,
        pending_withdrawals=pending_withdrawals,
        total_revenue=total_revenue,
        revenue_history=revenue_history,
        admin_net=admin_net,
        available_payout=available_payout
    )


