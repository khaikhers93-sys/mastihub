def init_db():
    conn = get_db()

    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            points INTEGER DEFAULT 0,
            today_points INTEGER DEFAULT 0,
            last_date TEXT
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS completed_missions (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            mission_id INTEGER NOT NULL,
            completed_date TEXT NOT NULL,
            UNIQUE(user_id, mission_id, completed_date)
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS withdrawals (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            amount INTEGER NOT NULL,
            points_used INTEGER NOT NULL,
            upi TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'Pending',
            created_at TEXT NOT NULL,
            utr TEXT,
            paid_at TEXT
        )
    """)

    conn.execute("""
        ALTER TABLE withdrawals
        ADD COLUMN IF NOT EXISTS utr TEXT
    """)

    conn.execute("""
        ALTER TABLE withdrawals
        ADD COLUMN IF NOT EXISTS paid_at TEXT
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS platform_revenue (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            amount REAL NOT NULL,
            source TEXT NOT NULL,
            created_at TEXT NOT NULL
        )
    """)

    # Digital Store products
    conn.execute("""
        CREATE TABLE IF NOT EXISTS store_products (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            description TEXT NOT NULL,
            price INTEGER NOT NULL,
            file_path TEXT NOT NULL,
            active BOOLEAN NOT NULL DEFAULT TRUE
        )
    """)

    # Add starter products only once
    products = [
        ("AI Video Prompts", "10 AI video ideas aur cinematic prompts", 29, "ai_video_prompts.txt"),
        ("Website Templates", "Website banane ke liye starter guide", 49, "website_templates.txt"),
        ("Instagram Creator Pack", "Hooks, captions aur hashtags", 29, "instagram_creator_pack.txt"),
    ]
    for name, description, price, filename in products:
        conn.execute(
            """
            INSERT INTO store_products (name, description, price, file_path)
            SELECT %s, %s, %s, %s
            WHERE NOT EXISTS (
                SELECT 1 FROM store_products WHERE file_path = %s
            )
            """,
            (name, description, price, filename, filename)
        )

    # Manual UPI orders; download access is granted only after admin verification
    conn.execute("""
        CREATE TABLE IF NOT EXISTS store_orders (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            amount INTEGER NOT NULL,
            status TEXT NOT NULL DEFAULT 'Pending',
            utr TEXT,
            created_at TEXT NOT NULL,
            verified_at TEXT
        )
    """)

    conn.commit()
    conn.close()



