@app.route("/mission/<int:mission_id>", methods=["GET", "POST"])
def mission(mission_id):
    if "user_id" not in session:
        return redirect(url_for("login"))

    if mission_id < 1 or mission_id > len(MISSIONS):
        return redirect(url_for("home"))

    conn = get_db()

    try:
        # Lock the user's row while processing a reward.
        user = conn.execute(
            "SELECT * FROM users WHERE id = %s FOR UPDATE",
            (session["user_id"],)
        ).fetchone()

        if not user:
            conn.rollback()
            session.clear()
            return redirect(url_for("login"))

        today = str(date.today())

        if user["last_date"] != today:
            conn.execute(
                """
                UPDATE users
                SET today_points = 0, last_date = %s
                WHERE id = %s
                """,
                (today, user["id"])
            )
            user = conn.execute(
                "SELECT * FROM users WHERE id = %s",
                (user["id"],)
            ).fetchone()

        already_done = conn.execute(
            """
            SELECT id FROM completed_missions
            WHERE user_id = %s AND mission_id = %s
            AND completed_date = %s
            """,
            (user["id"], mission_id, today)
        ).fetchone()

        if already_done:
            conn.commit()
            return redirect(url_for("home"))

        if user["today_points"] >= DAILY_LIMIT:
            conn.commit()
            return redirect(url_for("home"))

        if request.method == "POST":
            if request.form.get("completed") != "1":
                conn.rollback()
                return "Invalid game completion.", 400

            reward = min(
                MISSIONS[mission_id - 1][1],
                DAILY_LIMIT - user["today_points"]
            )

            # The database uniqueness rule prevents duplicate daily rewards.
            inserted = conn.execute(
                """
                INSERT INTO completed_missions
                    (user_id, mission_id, completed_date)
                VALUES (%s, %s, %s)
                ON CONFLICT (user_id, mission_id, completed_date)
                DO NOTHING
                RETURNING id
                """,
                (user["id"], mission_id, today)
            ).fetchone()

            if not inserted:
                conn.commit()
                return "Mission already completed.", 409

            conn.execute(
                """
                UPDATE users
                SET points = points + %s,
                    today_points = today_points + %s,
                    last_date = %s
                WHERE id = %s
                """,
                (reward, reward, today, user["id"])
            )
            conn.commit()
            return "OK", 200

        conn.commit()
        return render_template(
            "game.html",
            title=MISSIONS[mission_id - 1][0],
            points=MISSIONS[mission_id - 1][1],
            mission_id=mission_id
        )

    except Exception:
        conn.rollback()
        app.logger.exception("Mission processing failed")
        return "Game process nahi ho saka. Dobara try karo.", 500

    finally:
        conn.close()


@app.route("/withdraw", methods=["GET", "POST"])
def withdraw():

    if "user_id" not in session:
        return redirect(url_for("login"))

    conn = get_db()

    user = conn.execute(
        "SELECT * FROM users WHERE id = %s",
        (session["user_id"],)
    ).fetchone()

    if request.method == "POST":

        try:
            amount = int(request.form.get("amount", "0"))
        except ValueError:
            amount = 0

        upi = request.form.get("upi", "").strip()

        # 100 points = ₹10
        points_needed = amount * 10

        if amount < 10:
            conn.close()
            return render_template(
                "withdraw.html",
                user=user,
                error="Minimum withdrawal ₹10 है।"
            )

        if not upi:
            conn.close()
            return render_template(
                "withdraw.html",
                user=user,
                error="UPI ID डालें।"
            )

        if points_needed > user["points"]:
            conn.close()
            return render_template(
                "withdraw.html",
                user=user,
                error="आपके पास पर्याप्त points नहीं हैं।"
            )

        conn.execute(
            """
            INSERT INTO withdrawals
            (user_id, amount, points_used, upi, status, created_at)
            VALUES (%s, %s, %s, %s, 'Pending', %s)
            """,
            (
                user["id"],
                amount,
                points_needed,
                upi,
                str(date.today())
            )
        )

        conn.execute(
            """
            UPDATE users
            SET points = points - %s
            WHERE id = %s
            """,
            (points_needed, user["id"])
        )

        conn.commit()
        conn.close()

        return redirect(url_for("history"))

    conn.close()

    return render_template(
        "withdraw.html",
        user=user
    )


